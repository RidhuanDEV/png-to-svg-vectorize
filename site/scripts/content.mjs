// Collects the site's content from the repository (the single source of truth) before every build:
// version (pyproject.toml), changelog, user guides, theme tokens of the app, icons, and the latest
// GitHub release (download links, sizes, SHA-256). Output: src/generated/content.json + src/generated/theme.css.

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const site = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(site, "..");
const REPO = "RidhuanDEV/png-to-svg-vectorize";
const read = (p) => readFileSync(join(repo, p), "utf8").replace(/\r\n/g, "\n");

const version = /^version = "([^"]+)"/m.exec(read("pyproject.toml"))?.[1];
if (!version) throw new Error("version not found in pyproject.toml");

async function github(path) {
  const headers = { Accept: "application/vnd.github+json", "User-Agent": "pngsvg-site-build" };
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const res = await fetch(`https://api.github.com/repos/${REPO}${path}`, { headers });
  return res.ok ? res.json() : null;
}

/** Latest published release with its downloads and checksums; null when there is none (or no network). */
async function latestRelease() {
  try {
    const r = await github("/releases/latest");
    if (!r) return null;
    const sums = {};
    const sumAsset = r.assets.find((a) => a.name === "SHA256SUMS.txt");
    if (sumAsset) {
      const text = await (await fetch(sumAsset.browser_download_url)).text();
      for (const line of text.split("\n")) {
        const m = /^([0-9a-f]{64})\s+\*?(.+)$/.exec(line.trim());
        if (m) sums[m[2]] = m[1];
      }
    }
    return {
      tag: r.tag_name,
      date: r.published_at,
      url: r.html_url,
      assets: r.assets
        .filter((a) => a.name !== "SHA256SUMS.txt")
        .map((a) => ({ name: a.name, size: a.size, url: a.browser_download_url, sha256: sums[a.name] ?? null })),
    };
  } catch (e) {
    console.warn("release info unavailable:", e instanceof Error ? e.message : e);
    return null;
  }
}

// theme: the app's Paper & ink (light) and Lightbox (dark) tokens, as CSS variables
const themes = JSON.parse(read("app/ui/src/theme/themes.json"));
const vars = (tokens) =>
  Object.entries(tokens)
    .map(([k, v]) => `  --t-${k}: ${v};`)
    .join("\n");
const css = `/* generated by scripts/content.mjs from app/ui/src/theme/themes.json - do not edit */
:root {
${vars(themes.paper.tokens)}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root {
${vars(themes.lightbox.tokens)}
    color-scheme: dark;
  }
}
`;

mkdirSync(join(site, "src/generated"), { recursive: true });
writeFileSync(join(site, "src/generated/theme.css"), css);

const content = {
  version,
  changelog: read("CHANGELOG.md"),
  guide: { en: read("docs/user-guide.en.md"), id: read("docs/user-guide.id.md") },
  release: await latestRelease(),
  builtAt: new Date().toISOString().slice(0, 10),
};
// a published site must never lose its download links because of a transient API error
if (process.env.CI && !content.release) throw new Error("latest release could not be read from GitHub");
writeFileSync(join(site, "src/generated/content.json"), JSON.stringify(content, null, 1) + "\n");

// icons (screenshots are converted to WebP by scripts/assets.py and committed)
copyFileSync(join(repo, "assets/icons/icon-512.png"), join(site, "public/icon-512.png"));
copyFileSync(join(repo, "assets/icons/icon-256.png"), join(site, "public/icon-256.png"));
copyFileSync(join(repo, "app/ui/public/favicon.svg"), join(site, "public/favicon.svg"));

console.log(`content: v${version}, release ${content.release?.tag ?? "none"}`);
